"""Shared, dependency-light contracts for the local camera stream."""

from __future__ import annotations

from dataclasses import dataclass
import numpy as np


@dataclass(frozen=True)
class DeviceDetails:
    """Identify the capture source and its OAK hardware when connected."""

    product_name: str
    mxid: str
    usb_speed: str


@dataclass(frozen=True)
class StreamProfile:
    """Describe one reproducible camera capture configuration."""

    name: str
    width: int
    height: int
    fps: float


@dataclass(frozen=True)
class FramePacket:
    """Keep one image attached to the evidence describing its capture."""

    # Carry the original BGR pixels read from the camera or generated by the demo.
    image: np.ndarray
    sequence_number: int

    # OAK frames use device capture and host arrival times on the same clock.
    # Synthetic frames use generated host timestamps for repeatable tests.
    device_timestamp_s: float
    host_received_timestamp_s: float


# Map each supported profile name to its image size and requested frame rate.
_STREAM_PROFILES = {
    "480p20": StreamProfile(
        name="480p20",
        width=640,
        height=480,
        fps=20.0,
    ),
    "480p15": StreamProfile(
        name="480p15",
        width=640,
        height=480,
        fps=15.0,
    ),
    "480p25": StreamProfile(
        name="480p25",
        width=640,
        height=480,
        fps=25.0,
    ),
    "720p15": StreamProfile(
        name="720p15",
        width=1280,
        height=720,
        fps=15.0,
    ),
    "720p30": StreamProfile(
        name="720p30",
        width=1280,
        height=720,
        fps=30.0,
    ),
    "1080p30": StreamProfile(
        name="1080p30",
        width=1920,
        height=1080,
        fps=30.0,
    ),
}


# List the profile names the command-line runners accept.
STREAM_PROFILE_NAMES = tuple(_STREAM_PROFILES)


def get_stream_profile(profile_name: str) -> StreamProfile:
    """Return an approved profile or reject unsupported configurations."""

    try:
        return _STREAM_PROFILES[profile_name]

    except KeyError as error:
        # Report an unsupported profile name as a configuration error.
        raise ValueError(
            f"unsupported stream profile: {profile_name!r}",
        ) from error
